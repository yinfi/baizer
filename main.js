var VIEW_TYPE_GEMINI_SHELL = "gemini-shell-view";
var GeminiShellView = class extends import_obsidian4.ItemView {
  api;
  outputContainer;
  inputEl;
  suggestionContainer;
  currentSelection = "";
  editor = null;
  // Suggestion State
  isSuggesting = false;
  suggestionType = null;
  selectedIndex = 0;
  suggestions = [];
  // File Selection State
  pendingFileSelection = null;
  // Heartbeat monitoring
  heartbeatInterval = null;
  lastActivityTime = Date.now();
  heartbeatIntervalMs = 3e4;
  // 30秒检查一次
  isResponding = false;
  constructor(leaf, api) {
    super(leaf);
    this.api = api;
  }
  getViewType() {
    return VIEW_TYPE_GEMINI_SHELL;
  }
  getDisplayText() {
    return "Gemini Shell";
  }
  getIcon() {
    return "terminal-square";
  }
  async onOpen() {
    const { contentEl } = this;
    contentEl.empty();
    const container = contentEl.createDiv({ cls: "gemini-shell-view" });
    const header = container.createDiv({ cls: "shell-header" });
    header.createSpan({ text: "GEMINI SHELL" });
    const statusContainer = header.createDiv({ cls: "shell-status-container" });
    statusContainer.createSpan({ cls: "shell-status-dot" });
    statusContainer.createSpan({ text: "ONLINE" });
    this.outputContainer = container.createDiv({ cls: "shell-output-area" });
    this.appendLog("System", "Kernel initialized.", "system");
    const inputContainer = container.createDiv({ cls: "shell-input-container" });
    this.suggestionContainer = inputContainer.createDiv({ cls: "shell-suggestions" });
    const inputWrapper = inputContainer.createDiv({ cls: "shell-input-wrapper" });
    const promptIcon = inputWrapper.createSpan({ cls: "shell-prompt" });
    promptIcon.setText(">_");
    this.inputEl = inputWrapper.createEl("textarea", {
      cls: "shell-input",
      attr: {
        placeholder: "Ask Gemini... (/ for commands, @ for files)",
        spellcheck: "false",
        autocomplete: "off",
        rows: "1"
      }
    });
    const footer = inputContainer.createDiv({ cls: "shell-footer" });
    const rightActions = footer.createDiv({ cls: "action-group" });
    const createAction = (container2, key, label) => {
      const item = container2.createDiv({ cls: "action-item" });
      item.createSpan({ cls: "key-badge", text: key });
      item.createSpan({ cls: "action-label", text: label });
    };
    createAction(rightActions, "\u21B5", "Send");
    createAction(rightActions, "\u21E7\u21B5", "New Line");
    this.inputEl.addEventListener("input", () => {
      this.adjustHeight();
      this.handleInput();
    });
    this.inputEl.addEventListener("keydown", async (e) => {
      if (this.isSuggesting) {
        if (e.key === "ArrowUp") {
          e.preventDefault();
          this.navigateSuggestions(-1);
        } else if (e.key === "ArrowDown") {
          e.preventDefault();
          this.navigateSuggestions(1);
        } else if (e.key === "Enter") {
          e.preventDefault();
          this.selectSuggestion();
        } else if (e.key === "Escape") {
          e.preventDefault();
          this.hideSuggestions();
        }
        return;
      }
      if (e.key === "Enter" && !e.shiftKey) {
        e.preventDefault();
        if (e.isComposing)
          return;
        const query = this.inputEl.value.trim();
        if (!query)
          return;
        this.inputEl.value = "";
        this.adjustHeight();
        await this.processCommand(query);
      }
    });
    container.addEventListener("click", (e) => {
      if (window.getSelection()?.toString())
        return;
      if (e.target.closest(".shell-suggestions"))
        return;
      this.inputEl.focus();
    });
    this.startHeartbeat();
  }
  adjustHeight() {
    this.inputEl.style.height = "auto";
    this.inputEl.style.height = this.inputEl.scrollHeight + "px";
  }
  // ==================== Suggestion Logic ====================
  handleInput() {
    const val = this.inputEl.value;
    const cursor = this.inputEl.selectionStart;
    const textBeforeCursor = val.substring(0, cursor);
    const lastWord = textBeforeCursor.split(/\s+/).pop() || "";
    if (lastWord.startsWith("/")) {
      this.showSuggestions("command", lastWord.substring(1));
    } else if (lastWord.startsWith("@")) {
      this.showSuggestions("file", lastWord.substring(1));
    } else {
      this.hideSuggestions();
    }
  }
  showSuggestions(type, query) {
    this.isSuggesting = true;
    this.suggestionType = type;
    this.suggestionContainer.empty();
    this.suggestionContainer.style.display = "block";
    this.selectedIndex = 0;
    if (type === "command") {
      const commands = [
        { label: "/clear", desc: "Clear session history" },
        { label: "/profile", desc: "View user profile" },
        { label: "/forget", desc: "Forget context" },
        { label: "/new", desc: "Create new note" },
        { label: "/edit", desc: "Edit current selection" },
        { label: "/open", desc: "Open file" },
        { label: "/tools", desc: "List available MCP tools" }
      ];
      this.suggestions = commands.filter((c) => c.label.toLowerCase().includes(query.toLowerCase()));
    } else {
      const files = this.app.vault.getFiles();
      this.suggestions = files.filter((f) => f.path.toLowerCase().includes(query.toLowerCase())).slice(0, 10).map((f) => ({ label: f.basename, desc: f.path, value: `[[${f.path}]]` }));
    }
    if (this.suggestions.length === 0) {
      this.hideSuggestions();
      return;
    }
    this.renderSuggestions();
  }
  renderSuggestions() {
    this.suggestionContainer.empty();
    this.suggestions.forEach((item, index) => {
      const el = this.suggestionContainer.createDiv({
        cls: `suggestion-item ${index === this.selectedIndex ? "is-selected" : ""}`
      });
      el.createSpan({ cls: "suggestion-icon", text: this.suggestionType === "command" ? "/" : "@" });
      el.createSpan({ cls: "suggestion-text", text: item.label });
      if (item.desc) {
        el.createSpan({ cls: "suggestion-desc", text: item.desc });
      }
      el.addEventListener("click", () => {
        this.selectedIndex = index;
        this.selectSuggestion();
      });
    });
  }
  navigateSuggestions(dir) {
    this.selectedIndex += dir;
    if (this.selectedIndex < 0)
      this.selectedIndex = this.suggestions.length - 1;
    if (this.selectedIndex >= this.suggestions.length)
      this.selectedIndex = 0;
    this.renderSuggestions();
    const selectedEl = this.suggestionContainer.children[this.selectedIndex];
    if (selectedEl) {
      selectedEl.scrollIntoView({ block: "nearest" });
    }
  }
  selectSuggestion() {
    const item = this.suggestions[this.selectedIndex];
    if (!item)
      return;
    const val = this.inputEl.value;
    const cursor = this.inputEl.selectionStart;
    const textBeforeCursor = val.substring(0, cursor);
    const lastWord = textBeforeCursor.split(/\s+/).pop() || "";
    const replacement = this.suggestionType === "command" ? item.label : item.value;
    const newTextBefore = textBeforeCursor.substring(0, textBeforeCursor.length - lastWord.length) + replacement + " ";
    const newText = newTextBefore + val.substring(cursor);
    this.inputEl.value = newText;
    this.inputEl.selectionStart = this.inputEl.selectionEnd = newTextBefore.length;
    this.hideSuggestions();
    this.inputEl.focus();
  }
  hideSuggestions() {
    this.isSuggesting = false;
    this.suggestionContainer.style.display = "none";
    this.suggestionContainer.empty();
  }
  async processCommand(query) {
    this.appendLog("You", query, "user");
    if (this.pendingFileSelection && /^\d+$/.test(query)) {
      const index = parseInt(query) - 1;
      if (index >= 0 && index < this.pendingFileSelection.length) {
        await this.openFile(this.pendingFileSelection[index]);
        this.pendingFileSelection = null;
      } else {
        this.appendLog("System", `\u2717 \u65E0\u6548\u7684\u9009\u62E9\u3002\u8BF7\u8F93\u5165 1-${this.pendingFileSelection.length} \u4E4B\u95F4\u7684\u6570\u5B57`, "system");
      }
      return;
    }
    if (query.startsWith("/open ")) {
      const searchTerm = query.substring(6).trim();
      if (!searchTerm) {
        this.appendLog("System", "\u2717 \u8BF7\u63D0\u4F9B\u6587\u4EF6\u540D\u6216\u8DEF\u5F84\uFF0C\u4F8B\u5982\uFF1A/open readme", "system");
        return;
      }
      await this.handleOpenFile(searchTerm);
      return;
    }
    if (query === "/clear") {
      await this.api.clearSession();
      this.appendLog("System", "\u2713 \u4F1A\u8BDD\u5DF2\u6E05\u9664\uFF0C\u7528\u6237\u753B\u50CF\u4FDD\u7559", "system");
      return;
    }
    if (query === "/profile") {
      const profile = this.api.getUserProfile();
      if (!profile) {
        this.appendLog("System", "\u6682\u65E0\u7528\u6237\u753B\u50CF\u6570\u636E", "system");
        return;
      }
      let profileText = "## \u7528\u6237\u753B\u50CF\n\n";
      if (profile.name)
        profileText += `**\u59D3\u540D**: ${profile.name}
`;
      if (profile.profession)
        profileText += `**\u804C\u4E1A**: ${profile.profession}
`;
      if (profile.expertise.length > 0) {
        profileText += `**\u4E13\u4E1A\u9886\u57DF**: ${profile.expertise.join(", ")}
`;
      }
      if (profile.preferences.responseStyle) {
        profileText += `**\u56DE\u7B54\u98CE\u683C**: ${profile.preferences.responseStyle}
`;
      }
      this.appendLog("System", profileText, "system");
      return;
    }
    if (query === "/tools") {
      const tools = this.api.getAvailableTools();
      let toolsText = "## Available MCP Tools\n\n";
      tools.forEach((tool) => {
        toolsText += `### ${tool.name}
`;
        toolsText += `${tool.description}

`;
        if (tool.parameters && tool.parameters.properties) {
          toolsText += "**Parameters:**\n";
          Object.keys(tool.parameters.properties).forEach((param) => {
            const prop = tool.parameters.properties[param];
            const required = tool.parameters.required?.includes(param) ? " (required)" : "";
            toolsText += `- \`${param}\`${required}: ${prop.description || "No description"}
`;
          });
        }
        toolsText += "\n";
      });
      this.appendLog("System", toolsText, "system");
      return;
    }
    let contextStr = "";
    const activeFile = this.app.workspace.getActiveFile();
    if (activeFile) {
      contextStr = `Current Note: [[${activeFile.path}]]`;
    }
    const activeLeaf = this.app.workspace.getMostRecentLeaf();
    if (activeLeaf && activeLeaf.view) {
      const editor = activeLeaf.view.editor;
      if (editor) {
        this.editor = editor;
        this.currentSelection = editor.getSelection();
        if (this.currentSelection) {
          this.appendLog("System", `With selection (${this.currentSelection.length} chars)`, "system");
        }
      }
    }
    const loadingId = "loading-" + Date.now();
    const loadingDiv = this.outputContainer.createDiv({ cls: "shell-entry system" });
    loadingDiv.id = loadingId;
    loadingDiv.createSpan({ cls: "shell-loading" });
    loadingDiv.createSpan({ text: "Thinking..." });
    this.scrollToBottom();
    this.isResponding = true;
    try {
      this.updateActivity();
      const response = await this.api.chat(query, contextStr, this.currentSelection);
      const loader = document.getElementById(loadingId);
      if (loader)
        loader.remove();
      if (query.startsWith("/edit") && this.editor && this.currentSelection) {
        this.editor.replaceSelection(response);
        this.appendLog("System", "Text replaced.", "system");
      } else {
        this.appendLog("Gemini", response, "ai");
      }
    } catch (e) {
      const loader = document.getElementById(loadingId);
      if (loader)
        loader.remove();
      this.handleError(e, "Gemini API\u8C03\u7528");
    } finally {
      this.isResponding = false;
    }
  }
  appendLog(author, content, type) {
    const entry = this.outputContainer.createDiv({ cls: `shell-entry ${type}` });
    if (type === "ai") {
      import_obsidian4.MarkdownRenderer.render(this.app, content, entry, "", this);
    } else if (type === "user") {
      entry.setText(content);
    } else {
      entry.setText(`[${author}] ${content}`);
    }
    this.scrollToBottom();
    this.updateActivity();
  }
  scrollToBottom() {
    this.outputContainer.scrollTop = this.outputContainer.scrollHeight;
  }
  // ==================== File Opening Methods ====================
  async handleOpenFile(searchTerm) {
    const files = this.app.vault.getFiles();
    const matches = files.filter(
      (f) => f.path.toLowerCase().includes(searchTerm.toLowerCase()) || f.basename.toLowerCase().includes(searchTerm.toLowerCase())
    );
    if (matches.length === 0) {
      this.appendLog("System", `\u2717 \u672A\u627E\u5230\u5339\u914D "${searchTerm}" \u7684\u6587\u4EF6`, "system");
      return;
    }
    if (matches.length === 1) {
      await this.openFile(matches[0]);
      return;
    }
    this.showFileSelection(matches, searchTerm);
  }
  showFileSelection(files, searchTerm) {
    let message = `\u627E\u5230 ${files.length} \u4E2A\u5339\u914D "${searchTerm}" \u7684\u6587\u4EF6\uFF1A

`;
    files.forEach((f, i) => {
      message += `  ${i + 1}. ${f.path}
`;
    });
    message += "\n\u8F93\u5165\u6570\u5B57\u9009\u62E9\u6587\u4EF6";
    this.appendLog("System", message, "system");
    this.pendingFileSelection = files;
  }
  async openFile(file) {
    try {
      const leaf = this.app.workspace.getLeaf(false);
      await leaf.openFile(file);
      this.appendLog("System", `\u2713 \u5DF2\u6253\u5F00: ${file.path}`, "system");
      this.pendingFileSelection = null;
    } catch (e) {
      this.appendLog("System", `\u2717 \u6253\u5F00\u5931\u8D25: ${e.message}`, "system");
    }
  }
  async onClose() {
    this.stopHeartbeat();
  }
  // ==================== Heartbeat Monitoring ====================
  startHeartbeat() {
    this.heartbeatInterval = window.setInterval(() => {
      this.checkHeartbeat();
    }, this.heartbeatIntervalMs);
  }
  stopHeartbeat() {
    if (this.heartbeatInterval) {
      clearInterval(this.heartbeatInterval);
      this.heartbeatInterval = null;
    }
  }
  checkHeartbeat() {
    const now = Date.now();
    const timeSinceLastActivity = now - this.lastActivityTime;
    logger.debug(`\u5FC3\u8DF3\u68C0\u67E5: \u8DDD\u79BB\u4E0A\u6B21\u6D3B\u52A8 ${timeSinceLastActivity}ms`, "GeminiShellView.heartbeat");
    if (this.isResponding && timeSinceLastActivity > 12e4) {
      const warning = "\u26A0\uFE0F \u68C0\u6D4B\u5230\u957F\u65F6\u95F4\u65E0\u54CD\u5E94\uFF0C\u7CFB\u7EDF\u53EF\u80FD\u51FA\u73B0\u95EE\u9898";
      logger.warn(warning, "GeminiShellView.heartbeat");
      this.appendLog("System", warning, "system");
      this.isResponding = false;
    }
    if (timeSinceLastActivity > 3e5) {
      logger.info("\u957F\u65F6\u95F4\u65E0\u6D3B\u52A8\uFF0C\u91CD\u7F6E\u72B6\u6001", "GeminiShellView.heartbeat");
      this.isResponding = false;
    }
  }
  updateActivity() {
    this.lastActivityTime = Date.now();
    this.isResponding = true;
    logger.debug(`\u6D3B\u52A8\u66F4\u65B0: ${(/* @__PURE__ */ new Date()).toISOString()}`, "GeminiShellView.updateActivity");
  }
  // ==================== Enhanced Error Handling ====================
  handleError(error, context) {
    logger.error(`${context} \u9519\u8BEF`, error, "GeminiShellView", { context });
    const errorMessage = this.formatErrorMessage(error, context);
    this.appendLog("Error", errorMessage, "system");
    this.isResponding = false;
  }
  formatErrorMessage(error, context) {
    if (error.name === "AbortError") {
      return `${context}: \u8BF7\u6C42\u8D85\u65F6\uFF0C\u8BF7\u7A0D\u540E\u91CD\u8BD5`;
    }
    if (error.message?.includes("503") || error.message?.includes("overloaded")) {
      return `${context}: AI\u6A21\u578B\u5F53\u524D\u8FC7\u8F7D\uFF0C\u8BF7\u7A0D\u540E\u518D\u8BD5`;
    }
    if (error.message?.includes("401")) {
      return `${context}: API\u5BC6\u94A5\u65E0\u6548\u6216\u5DF2\u8FC7\u671F`;
    }
    if (error.message?.includes("network")) {
      return `${context}: \u7F51\u7EDC\u8FDE\u63A5\u95EE\u9898\uFF0C\u8BF7\u68C0\u67E5\u7F51\u7EDC\u8FDE\u63A5`;
    }
    return `${context}: ${error.message || "\u672A\u77E5\u9519\u8BEF"}`;
  }
};

// src/ui/guardian-gutter.ts
var import_view = require("@codemirror/view");
var import_state = require("@codemirror/state");
var setGuardianMode = import_state.StateEffect.define();
var setGuardianLineState = import_state.StateEffect.define();
var guardianModeField = import_state.StateField.define({
  create() {
    return true;
  },
  update(value, tr) {
    for (let effect of tr.effects) {
      if (effect.is(setGuardianMode)) {
        return effect.value;
      }
    }
    return value;
  }
});
var guardianLineStateField = import_state.StateField.define({
  create() {
    return null;
  },
  update(value, tr) {
    for (let effect of tr.effects) {
      if (effect.is(setGuardianLineState)) {
        return effect.value;
      }
    }
    if (tr.docChanged) {
      return null;
    }
    return value;
  }
});
var GuardianDotMarker = class extends import_view.GutterMarker {
  constructor(state, view) {
    super();
    this.state = state;
    this.view = view;
  }
  toDOM() {
    const dot = document.createElement("div");
    dot.className = `guardian-gutter-marker guardian-${this.state}`;
    dot.onclick = (e) => {
      e.preventDefault();
      e.stopPropagation();
      const currentMode = this.view.state.field(guardianModeField);
      this.view.dispatch({
        effects: setGuardianMode.of(!currentMode)
      });
    };
    switch (this.state) {
      case "thinking" /* Thinking */:
        dot.title = "Guardian is analyzing...";
        break;
      case "has-suggestion" /* HasSuggestion */:
        dot.title = "Guardian has a suggestion (Tab to accept)";
        break;
      case "paused" /* Paused */:
        dot.title = "Guardian is Paused (Click to Resume)";
        break;
      case "idle" /* Idle */:
        dot.title = "Guardian is Active (Click to Pause)";
        break;
    }
    return dot;
  }
};
var guardianMarkerField = import_state.StateField.define({
  create() {
    return import_state.RangeSet.empty;
  },
  update(markers, tr) {
    const isEnabled = tr.state.field(guardianModeField);
    const localState = tr.state.field(guardianLineStateField);
    let effectiveState = "idle" /* Idle */;
    if (!isEnabled) {
      effectiveState = "paused" /* Paused */;
    } else if (localState && localState.state) {
      effectiveState = localState.state;
    }
    const selection = tr.state.selection.main;
    const lineBlock = tr.state.doc.lineAt(selection.head);
    const marker = new GuardianDotMarker(effectiveState, null);
    return import_state.RangeSet.of([marker.range(lineBlock.from)]);
  }
});
function guardianGutterExtension() {
  return [
    guardianModeField,
    guardianLineStateField,
    guardianMarkerField,
    (0, import_view.gutter)({
      class: "guardian-gutter",
      markers: (view) => view.state.field(guardianMarkerField),
      domEventHandlers: {
        mousedown(view, line, event) {
          const target = event.target;
          if (target.classList.contains("guardian-gutter-marker")) {
            event.preventDefault();
            const currentMode = view.state.field(guardianModeField);
            view.dispatch({
              effects: setGuardianMode.of(!currentMode)
            });
            return true;
          }
          return false;
        }
      }
    })
  ];
}
function updateGuardianState(view, line, state) {
  view.dispatch({
    effects: setGuardianLineState.of({ line, state })
  });
}

// src/ui/ghost-text.ts
var import_view2 = require("@codemirror/view");
var import_state2 = require("@codemirror/state");
var import_state3 = require("@codemirror/state");
var import_state4 = require("@codemirror/state");
var setGhostText = import_state2.StateEffect.define();
var GhostTextWidget = class extends import_view2.WidgetType {
  constructor(text) {
    super();
    this.text = text;
  }
  toDOM() {
    const span = document.createElement("span");
    span.className = "guardian-ghost-text";
    span.textContent = this.text;
    span.setAttribute("aria-label", "Press Tab to accept suggestion");
    return span;
  }
  ignoreEvent() {
    return false;
  }
};
var ghostTextField = import_state2.StateField.define({
  create() {
    return import_view2.Decoration.none;
  },
  update(decorations, tr) {
    for (let effect of tr.effects) {
      if (effect.is(setGhostText)) {
        if (effect.value) {
          const { text, line, ch } = effect.value;
          if (line < 1 || line > tr.state.doc.lines) {
            continue;
          }
          const lineBlock = tr.state.doc.line(line);
          const pos = Math.min(lineBlock.from + ch, lineBlock.to);
          const widget = import_view2.Decoration.widget({
            widget: new GhostTextWidget(text || ""),
            side: 1
          });
          return import_view2.Decoration.set([widget.range(pos)]);
        } else {
          return import_view2.Decoration.none;
        }
      }
    }
    if (tr.docChanged) {
      return import_view2.Decoration.none;
    }
    return decorations.map(tr.changes);
  },
  provide: (f) => import_view2.EditorView.decorations.from(f)
});
var ghostTextStateField = import_state2.StateField.define({
  create() {
    return null;
  },
  update(value, tr) {
    for (let effect of tr.effects) {
      if (effect.is(setGhostText)) {
        return effect.value;
      }
    }
    if (tr.docChanged)
      return null;
    return value;
  }
});
function acceptGhostTextReal(view) {
  const suggestion = view.state.field(ghostTextStateField);
  if (!suggestion)
    return false;
  const { text, replaceRange, line, ch } = suggestion;
  let from = replaceRange ? replaceRange.from : 0;
  let to = replaceRange ? replaceRange.to : 0;
  if (!replaceRange) {
    const lineBlock = view.state.doc.line(line);
    from = Math.min(lineBlock.from + ch, lineBlock.to);
    to = from;
  }
  view.dispatch({
    changes: { from, to, insert: text },
    selection: import_state3.EditorSelection.cursor(from + text.length),
    effects: setGhostText.of(null)
  });
  return true;
}
var ghostTextKeymap = import_state4.Prec.highest(import_view2.keymap.of([
  {
    key: "Tab",
    run: (view) => {
      return acceptGhostTextReal(view);
    }
  },
  {
    key: "Escape",
    run: (view) => {
      const suggestion = view.state.field(ghostTextStateField);
      if (suggestion) {
        view.dispatch({
          effects: setGhostText.of(null)
        });
        return true;
      }
      return false;
    }
  }
]));
