const outputDir = "dist";

async function copyStaticAssets() {
	await mkdir(outputDir, { recursive: true });
	await Promise.all([
		copyFile("manifest.json", `${outputDir}/manifest.json`),
		copyFile("styles.css", `${outputDir}/styles.css`),
	]);
}

