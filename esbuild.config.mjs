import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "module";
import { copyFile, mkdir, readFile } from "fs/promises";

const outputDir = "dist";

async function copyStaticAssets() {
	await mkdir(outputDir, { recursive: true });
	await Promise.all([
		copyFile("manifest.json", `${outputDir}/manifest.json`),
		copyFile("styles.css", `${outputDir}/styles.css`),
	]);
}

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

/**
 * 把用不到的 pi-ai provider 换成存根，避免它们的 SDK 进入 bundle。
 *
 * 背景：pi-ai 的 providers/register-builtins.js 会为全部 9 个 provider 注册
 * 惰性加载器，每个都是 `import("./<provider>.js")`。esbuild 在 format: "cjs"
 * 下无法做 code splitting，于是把这些动态 import 全部内联进单文件 —— 哪怕
 * 运行时永远走不到。
 *
 * Baizer 的 ProviderConfig 只有 'gemini' 和 'openai-compatible' 两种
 * （见 src/mcp/types.ts），传给 pi 的 api 只会是 google-generative-ai 或
 * openai-completions。Mistral 的 1.2MB SDK 是纯死重量。
 *
 * 这里不改上游代码，只在打包层把该模块解析到一个存根：导出同名函数，被调用
 * 时抛出可读错误。如果将来真要支持 Mistral，从这个列表里移除即可。
 *
 * 为什么在意体积：Obsidian Sync Standard 计划不同步超过 5MB 的文件，
 * 而 main.js 原本是 6.0MB —— 这会让付费同步用户拿不到插件更新。
 */
const STUBBED_PI_PROVIDERS = [
	{ file: "mistral.js", exports: ["streamMistral", "streamSimpleMistral"] },
];

const stubUnusedPiProviders = {
	name: "stub-unused-pi-providers",
	setup(build) {
		for (const { file, exports } of STUBBED_PI_PROVIDERS) {
			// 只匹配 pi-ai 自己 providers 目录下的相对 import，避免误伤同名文件。
			const filter = new RegExp(`^\\./${file.replace(".", "\\.")}$`);
			build.onResolve({ filter }, (args) => {
				if (!args.importer.includes("pi-ai")) return null;
				return { path: `pi-provider-stub:${file}`, namespace: "pi-stub" };
			});
		}

		build.onLoad({ filter: /.*/, namespace: "pi-stub" }, (args) => {
			const file = args.path.replace("pi-provider-stub:", "");
			const entry = STUBBED_PI_PROVIDERS.find((p) => p.file === file);
			const name = file.replace(".js", "");
			const contents = entry.exports
				.map(
					(fn) => `export function ${fn}() {
	throw new Error(
		"Baizer does not bundle the '${name}' provider. " +
		"Configure a Gemini or OpenAI-compatible provider instead."
	);
}`,
				)
				.join("\n");
			return { contents, loader: "js" };
		});
	},
};

/**
 * 关掉 pi-ai 对 node 内建模块的 eager 动态 import，消除启动时的三条
 * unhandled rejection。
 *
 * 背景：pi-ai 的 env-api-keys.js 与 providers/openai-codex-responses.js 用
 * `"node:" + "fs"` 这种字符串拼接来躲开打包器的静态分析（源码注释写着
 * "NEVER convert to top-level imports - breaks browser/Vite builds"），再靠
 * `process.versions.node` 判断是否处于 Node 环境后 eager 加载。
 *
 * 但 Obsidian 是 Electron 渲染进程：`process.versions.node` 存在，判据通过，
 * 而模块解析走浏览器 ESM 通道，于是 `import("node:fs")` 被当作 URL 去 fetch
 * 并必然失败。三个 Promise 无人 catch，冒泡到 window 的 unhandledrejection，
 * 被 ModelService 的全局钩子记成 ERROR —— 每次启动刷三条，会掩盖真正的报错。
 *
 * 为什么不能在 onResolve 拦：拼接出的 specifier 是运行时变量
 * （`import(__rewriteRelativeImportExtension(specifier))`），构建期没有字面量
 * 可匹配，onResolve 永远不命中。external 同样拦不住 —— builtinModules 只含裸名
 * fs/os/path，不含 node: 前缀形式。所以改在 onLoad 层把那个环境判据置为 false，
 * 让 eager 加载根本不启动。
 *
 * 安全性：置 false 后 _existsSync / _homedir / _join / _os 保持 null，与「加载
 * 失败」的终态完全一致，只是不再抛。两处消费点本就对此做了兜底 —— env-api-keys
 * 在 `!_existsSync || !_homedir || !_join` 时提前返回，codex 用
 * `_os ? ... : "pi (browser)"`。它们服务的是「从 ~/.config 读第三方 CLI 凭据」
 * 与 UA 拼装，而 Baizer 的 key 全部来自 settings，本就走不到这条路径。
 */
const NODE_EAGER_LOAD_GUARD =
	'if (typeof process !== "undefined" && (process.versions?.node || process.versions?.bun)) {';

const stubNodeBuiltinDynamicImports = {
	name: "stub-node-builtin-dynamic-imports",
	setup(build) {
		build.onLoad(
			{ filter: /(env-api-keys|providers[\\/]openai-codex-responses)\.js$/ },
			async (args) => {
				if (!args.path.includes("pi-ai")) return null;

				const source = await readFile(args.path, "utf8");
				const occurrences = source.split(NODE_EAGER_LOAD_GUARD).length - 1;
				// 出声失败而非静默放过：pi-ai 升级若改了这段判据的写法，这里必须让构建
				// 红掉，否则那三条启动期 ERROR 会悄悄回来。
				if (occurrences !== 1) {
					throw new Error(
						`stub-node-builtin-dynamic-imports: expected exactly 1 eager-load guard in ${args.path}, found ${occurrences}. `
						+ `pi-ai 可能改了写法，请重新核对 env-api-keys.js / openai-codex-responses.js。`,
					);
				}

				return {
					contents: source.replace(NODE_EAGER_LOAD_GUARD, "if (false) {"),
					loader: "js",
				};
			},
		);
	},
};

const prod = (process.argv[2] === "production");

await mkdir(outputDir, { recursive: true });

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: `${outputDir}/main.js`,
	loader: { '.md': 'text' },
	plugins: [stubUnusedPiProviders, stubNodeBuiltinDynamicImports],
});

if (prod) {
	await context.rebuild();
	await copyStaticAssets();
	process.exit(0);
} else {
	await copyStaticAssets();
	await context.watch();
}
