/**
 * 去掉 pi-ai 1.3.0 源码里的 JSON import attributes（`with { type: "json" }`）。
 *
 * 背景：pi-ai 1.3.0 的 `providers/all.js` 与每个 `providers/<x>.models.js` 都写成
 *   `import values from "./data/x.json" with { type: "json" };`
 * 本项目锁定的 esbuild@0.17.19 不支持该语法（import attributes 是后续版本才支持的），
 * 会在解析阶段直接报 `Expected ";" but found "with"`，整个构建失败。
 *
 * 为什么可以安全剥掉：`.json` 的解析本就由 esbuild 按扩展名走 json loader，
 * 这个 attribute 对打包结果没有任何影响（它服务的是原生 Node ESM 的运行时断言）。
 * 剥掉后语义等价。
 *
 * 为什么在 onLoad 而不是 onResolve：语法错误发生在解析阶段，onResolve 拦不到；
 * 只能读源码、改写、再交给 esbuild。
 *
 * 出声失败：若某个文件里出现了该语法却没被剥掉（例如 pi-ai 换了写法），
 * 这里必须让构建红掉，而不是留下一个"看起来成功"的包。
 */
const JSON_IMPORT_ATTRIBUTE = /\s+with\s*\{\s*type:\s*["']json["']\s*\}/g;

const stripJsonImportAttributes = {
	name: "strip-json-import-attributes",
	setup(build) {
		build.onLoad({ filter: /pi-ai[\\/]dist[\\/].*\.js$/ }, async (args) => {
			const source = await readFile(args.path, "utf8");
			const stripped = source.replace(JSON_IMPORT_ATTRIBUTE, "");
			// 无该语法时原样返回，让 esbuild 走默认 loader（省掉无谓的重新解析）。
			if (stripped === source) return null;

			const leftover = stripped.match(/\bwith\s*\{\s*type:/g);
			if (leftover) {
				throw new Error(
					`strip-json-import-attributes: ${args.path} 仍残留 ${leftover.length} 处未识别的 import attribute 写法。`
					+ `pi-ai 可能改了语法，请重新核对。`,
				);
			}
			return { contents: stripped, loader: "js" };
		});
	},
};

/**
 * 关掉 pi-ai 对 node 内建模块的 eager 动态 import，消除启动时的三条
 * unhandled rejection。
 *
 * 背景：pi-ai 的 env-api-keys.js 与 providers/openai-codex-responses.js 用
 * `"node:" + "fs"` 这种字符串拼接来躲开打包器的静态分析（源码注释写着
 * "NEVER convert to top-level imports - breaks browser/Vite builds"），再靠
 * `process.versions.node` 判断是否处于 Node 环境后 eager 加载。
 *
 * 但 Obsidian 是 Electron 渲染进程：`process.versions.node` 存在，判据通过，
 * 而模块解析走浏览器 ESM 通道，于是 `import("node:fs")` 被当作 URL 去 fetch
 * 并必然失败。三个 Promise 无人 catch，冒泡到 window 的 unhandledrejection，
 * 被 ModelService 的全局钩子记成 ERROR —— 每次启动刷三条，会掩盖真正的报错。
 *
 * 为什么不能在 onResolve 拦：拼接出的 specifier 是运行时变量
 * （`import(__rewriteRelativeImportExtension(specifier))`），构建期没有字面量
 * 可匹配，onResolve 永远不命中。external 同样拦不住 —— builtinModules 只含裸名
 * fs/os/path，不含 node: 前缀形式。所以改在 onLoad 层把那个环境判据置为 false，
 * 让 eager 加载根本不启动。
 *
 * 安全性：置 false 后 _existsSync / _homedir / _join / _os 保持 null，与「加载
 * 失败」的终态完全一致，只是不再抛。两处消费点本就对此做了兜底 —— env-api-keys
 * 在 `!_existsSync || !_homedir || !_join` 时提前返回，codex 用
 * `_os ? ... : "pi (browser)"`。它们服务的是「从 ~/.config 读第三方 CLI 凭据」
 * 与 UA 拼装，而 Baizer 的 key 全部来自 settings，本就走不到这条路径。
 */
const NODE_EAGER_LOAD_GUARD =
	'if (typeof process !== "undefined" && (process.versions?.node || process.versions?.bun)) {';

const stubNodeBuiltinDynamicImports = {
	name: "stub-node-builtin-dynamic-imports",
	setup(build) {
		build.onLoad(
			{ filter: /(env-api-keys|providers[\\/]openai-codex-responses)\.js$/ },
			async (args) => {
				if (!args.path.includes("pi-ai")) return null;

				const source = await readFile(args.path, "utf8");
				const occurrences = source.split(NODE_EAGER_LOAD_GUARD).length - 1;
				// 出声失败而非静默放过：pi-ai 升级若改了这段判据的写法，这里必须让构建
				// 红掉，否则那三条启动期 ERROR 会悄悄回来。
				if (occurrences !== 1) {
					throw new Error(
						`stub-node-builtin-dynamic-imports: expected exactly 1 eager-load guard in ${args.path}, found ${occurrences}. `
						+ `pi-ai 可能改了写法，请重新核对 env-api-keys.js / openai-codex-responses.js。`,
					);
				}

				return {
					contents: source.replace(NODE_EAGER_LOAD_GUARD, "if (false) {"),
					loader: "js",
				};
			},
		);
	},
};

const prod = (process.argv[2] === "production");

await mkdir(outputDir, { recursive: true });

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: `${outputDir}/main.js`,
	loader: { '.md': 'text' },
	plugins: [
		stubUnusedPiProviders,
		stubUnusedPiApis,
		stripJsonImportAttributes,
		stubNodeBuiltinDynamicImports,
	],
});

if (prod) {
	await context.rebuild();
	await copyStaticAssets();
	process.exit(0);
} else {
	await copyStaticAssets();
	await context.watch();
}
